from vision_check.models import Box, Draw
from vision_check.parts import part_draws, part_masks


def test_lower_door_component_maps_to_screen_and_excludes_window() -> None:
    image = np.full((100, 100, 4), (180, 170, 140, 255), dtype=np.uint8)
    image[68:96, 45:57, :3] = 30
    image[20:40, 20:30, :3] = 30
    draw = Draw(asset="/house.png", box=Box(x=50, y=80, width=200, height=200), order=3)
    result = part_draws(draw, image)
    assert len(result) == 1
    part, mask = result[0]
    assert part.box == Box(x=140, y=216, width=24, height=56)
    assert part.asset.startswith("door-opening:")
    assert mask.shape == (28, 12)
    assert list(part_masks(result)) == [part.asset]


def test_connected_timber_and_unknown_asset_abstain() -> None:
    image = np.full((100, 100, 4), (180, 170, 140, 255), dtype=np.uint8)
    image[:, 45:49, :3] = 30
    image[70:74, :, :3] = 30
    draw = Draw(asset="/house.png", box=Box(x=0, y=0, width=100, height=100), order=1)
    assert not part_draws(draw, image)
    image[65:90, 55:67, :3] = 30
    assert not part_draws(draw.model_copy(update={"asset": "/terrain.png"}), image)


def test_dark_wheel_rim_detected_but_solid_disc_abstains() -> None:
    image = np.full((100, 160, 4), (180, 170, 140, 255), dtype=np.uint8)
    cv2.circle(image, (50, 75), 15, (30, 30, 30, 255), 3)
    draw = Draw(asset="/cart.png", box=Box(x=0, y=0, width=160, height=100), order=1)
    result = part_draws(draw, image)
    assert result
    assert all(part.asset.startswith("cart-wheel:") for part, _mask in result)
    image[:, :, :3] = 180
    cv2.circle(image, (50, 75), 15, (30, 30, 30, 255), -1)
    assert not part_draws(draw, image)


def test_perspective_outer_ellipse_detects_whole_wheel() -> None:
    image = np.full((100, 160, 4), (180, 170, 140, 255), dtype=np.uint8)
    cv2.ellipse(image, (65, 70), (12, 21), 20, 0, 360, (30, 30, 30, 255), 3)
    draw = Draw(asset="/cart.png", box=Box(x=0, y=0, width=160, height=100), order=1)
    result = part_draws(draw, image)
    assert result
    assert all(part.box.height >= 35 for part, _mask in result)


