import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';
const model = fileURLToPath(new URL('../model/', import.meta.url));
const excluded = new Set(['session.ts', 'build-identity.ts']);
const paths = (await readdir(model, { recursive: true })).filter(path => path.endsWith('.ts') && !excluded.has(path)).sort();
const files = await Promise.all(paths.map(async path => ({ path, sha256: createHash('sha256').update(await readFile(join(model, path))).digest('hex') })));
const hash = subset => createHash('sha256').update(JSON.stringify(subset)).digest('hex');
const identity = {
 format: 1,
 sourceHash: hash(files),
 rulesHash: hash(files.filter(file => file.path === 'rules.ts')),
 contentHash: hash(files.filter(file => file.path === 'terrain.ts')),
};
const generated = `// Generated by scripts/build-identity.mjs; regenerate after model source edits.\n// Local reproducibility identity, not an authentication signature.\nexport const BUILD_IDENTITY = ${JSON.stringify(identity, null, 2)} as const;\nexport const BUILD_SOURCES = ${JSON.stringify(files, null, 2)} as const;\n`;
const destination = join(model, 'build-identity.ts');
if (process.argv.includes('--check')) {
 const existing = await readFile(destination, 'utf8');
 if (existing !== generated) {
  process.stderr.write('Stale simulation build identity. Run node prototype/scripts/build-identity.mjs before compiling.\n');
  process.exitCode = 1;
 } else process.stdout.write(`Build identity current: ${identity.sourceHash} (${files.length} model files)\n`);
} else {
 await writeFile(destination, generated);
 process.stdout.write(`Generated ${relative(process.cwd(), destination)}: ${identity.sourceHash}\n`);
}
